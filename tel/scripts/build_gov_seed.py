#!/usr/bin/env python3
"""Build seed/government_seed.sql from seed/government_numbers.json.

government_numbers.json entries (collected from official *.go.jp pages only — every
number must have been seen on the page in source_url; unverified agencies are
excluded upstream, never guessed):
  {agency, agency_short, number (as published, may contain hyphens),
   number_kind （代表番号/相談窓口/…), source_url, note}
"""
import json, re, pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((HERE / 'seed' / 'government_numbers.json').read_text(encoding='utf-8'))
VERIFIED_ON = '2026-10-22'

def q(s):
    if s is None:
        return 'NULL'
    return "'" + str(s).replace("'", "''") + "'"

def digits(s):
    d = re.sub(r'\D', '', str(s))
    if d.startswith('81') and len(d) in (11, 12):  # +81 international form
        d = '0' + d[2:]
    return d

def agency_kind(name):
    for suf in ('省', '庁', '委員会', '府', '院', '銀行', '図書館'):
        if name.endswith(suf):
            return suf
    return 'その他'

def num_kind(k):
    if k and '相談' in k:
        return '相談窓口'
    if k and ('代表' in k):
        return '代表'
    return 'その他'

agencies = {}
out = ['-- GENERATED by scripts/build_gov_seed.py — do not edit by hand.']
n = 0
for e in data:
    name = e['agency']
    if name not in agencies:
        agencies[name] = len(agencies) + 1
        out.append(
            "INSERT INTO government_agency (id, name, name_short, kind, url) VALUES "
            f"({agencies[name]},{q(name)},{q(e.get('agency_short') or name)},{q(agency_kind(name))},NULL);"
        )
    d = digits(e['number'])
    if not d.startswith('0') or len(d) < 9:
        continue
    out.append(
        "INSERT OR IGNORE INTO government_number (number, agency_id, number_kind, label, source_url, verified_on) VALUES "
        f"({q(d)},{agencies[name]},{q(num_kind(e.get('number_kind')))},{q(e.get('note') if e.get('note') != 'なし' else None)},{q(e['source_url'])},{q(VERIFIED_ON)});"
    )
    n += 1

(HERE / 'seed' / 'government_seed.sql').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f"government_seed.sql written: {len(agencies)} agencies, {n} numbers")
