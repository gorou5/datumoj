def test_all_banks_pass_together(maple_m3, capsys):
    deps = maple_m3["deps"]
    questions = [q for q in load_questions(ROOT / "eval/questions") if Path(q._source_file).stem in BANKS]
    counts = Counter(Path(q._source_file).stem for q in questions)
    assert set(counts) == set(BANKS)
    assert sum(counts[b] for b in BANKS[:4]) >= 60
    assert sum(counts[b] for b in BANKS[4:7]) == 25
    assert sum(counts[b] for b in BANKS[7:]) == 33

    def cite(citation):
        answer = deps.tools.cite(citation.snapshot_sha256, citation.locator,
                                 snapshot_id=citation.snapshot_id, resource_url=citation.resource_url)
        assert answer["data"]["status"] == "ok"
        return answer["data"]["passages"]

    report = evaluate(questions, retriever=deps.retriever, observation_store=deps.observations,
                      cite=cite, manifest=deps.manifest, catalog=deps.catalog,
                      list_changes=deps.tools.list_changes)
    for row in [*report.questions, *report.failures]:
        row["file"] = f"eval/questions/{Path(row['file']).name}"
    write_reports(report, maple_m3["evidence"])
    gate = check_gate(report)
    failures, scores = list(gate.failures), {}
    # Enforce each applicable metric per bank; absent metrics are explicitly
    # N/A, never converted to perfect scores or used to hide another bank.
    for bank in BANKS:
        rows = [r for r in report.questions if Path(r["file"]).stem == bank]
        metrics = {}
        thresholds = {**gate.thresholds, **({"recall_at_10": 0.8, "gap_accuracy": 1.0}
                                           if bank.startswith("maple_") else {})}
        for metric, threshold in thresholds.items():
            values = [r["metrics"][metric] for r in rows if r["metrics"][metric] is not None]
            value = sum(values) / len(values) if values else None
            metrics[metric] = {"value": value, "threshold": threshold, "evaluated": len(values)}
            if value is not None and value < threshold:
                failures.append(f"{bank}: {metric}={value:.3f} < {threshold:.3f}")
        scores[bank] = {"questions": len(rows), "metrics": metrics}
    _json(maple_m3["evidence"] / "scores.json", scores)
    _json(maple_m3["evidence"] / "gate.json", {"passed": not failures, "failures": failures,
                                             "overall": report.overall, "thresholds": gate.thresholds})
    with capsys.disabled():
        print("\nAUDIT 149 ALL BANK SCORES\n" + json.dumps(scores, ensure_ascii=False, indent=2))
    assert not failures, (failures, report.failures)



def test_backfill_vectors_and_storage(maple_m3, tmp_path, capsys):
    import sqlite3
    from dataclasses import replace

    from datumoj.rikolto.core.state import _vector_coverage
    from datumoj.rikolto.index.fts import SqliteKeywordIndex
    from datumoj.rikolto.index.projections import is_projection
    from datumoj.rikolto.index.vector import LanceVectorIndex
    from datumoj.rikolto.store.chunks import SqliteChunkStore
    from datumoj.rikolto.testing.fakes import FakeEmbedder

    deps = maple_m3["deps"]
    current = list(deps.chunks.iter_chunks())
    projected = [chunk for chunk in current if is_projection(chunk)]
    assert projected
    body = [chunk for chunk in current if not is_projection(chunk)]
    eligible_body = [chunk for chunk in body if deps.registry.get(chunk.source_id).scope.get("embed", True)]
    path = tmp_path / "chunks.sqlite"
    with sqlite3.connect(deps.data_dir / "chunks.sqlite") as source, sqlite3.connect(path) as target:
        source.backup(target)
    with sqlite3.connect(path) as db:
        db.execute("VACUUM")
        full_bytes = path.stat().st_size
        stored = [json.loads(row[0]) for row in db.execute("SELECT chunk_json FROM chunks")]
        all_projected = [row for row in stored if row["chunk_id"].startswith(row["doc_key"] + "#projection:")]
        db.execute("DELETE FROM chunks WHERE instr(chunk_id, doc_key || '#projection:') = 1")
        db.execute("DELETE FROM documents WHERE json_extract(document_json, '$.metadata.projection') = 'keyword'")
        db.execute("DELETE FROM current_versions WHERE NOT EXISTS (SELECT 1 FROM documents d "
                   "WHERE d.doc_key = current_versions.doc_key AND d.snapshot_sha256 = current_versions.snapshot_sha256)")
        db.execute("DELETE FROM published_orders WHERE doc_key NOT IN (SELECT doc_key FROM current_versions)")
        db.commit()
        db.execute("VACUUM")
    legacy_bytes = path.stat().st_size

    class Unavailable:
        def __getattr__(self, name):
            raise AssertionError(f"Backfill accessed raw/parser: {name}")

    chunks = SqliteChunkStore(path)
    keyword = SqliteKeywordIndex(tmp_path / "keyword.sqlite")
    vectors = LanceVectorIndex(tmp_path / "vectors", FakeEmbedder())
    migrated = replace(deps.pipeline_deps, chunks=chunks, keyword=keyword, vectors=vectors,
                       raw=Unavailable(), parsers={}, vector_state_path=tmp_path / "vectors-state.json",
                       vector_state={"missing": {}, "last_error": None}, vector_limit=None)
    try:
        assert pipeline.backfill_projections(migrated) > 0
        restored = list(chunks.iter_chunks())
        # CatalogStore keeps one metadata version. Metadata from a different
        # snapshot cannot be copied into the row snapshot during migration.
        assert {c.chunk_id for c in restored if "#projection:row:" in c.chunk_id} == {
            c.chunk_id for c in projected if "#projection:row:" in c.chunk_id
        }
        for chunk in restored:
            if "#projection:entry:" in chunk.chunk_id:
                assert deps.catalog.get_dataset(chunk.doc_key).snapshot_sha256 == chunk.snapshot_sha256
        assert {c.chunk_id for c in restored if not is_projection(c)} == {c.chunk_id for c in body}
        pipeline.reindex(migrated)
        assert vectors.count_rows() == len(eligible_body)
        assert {hit.chunk_id for hit in vectors.search("catalog", k=len(body)).items} == {
            chunk.chunk_id for chunk in eligible_body
        }
        assert pipeline.vector_status(migrated) == {"state": "available", "blocks": len(restored)}
        assert pipeline.reindex(migrated, vectors_only=True) == 0
        before = {c.chunk_id: c.model_dump_json() for c in chunks.iter_chunks()}
        coverage = _vector_coverage(tmp_path)
        assert coverage.embedded_chunks == len(eligible_body) and coverage.pending_chunks == 0
        assert pipeline.backfill_projections(migrated) == 0
        assert before == {c.chunk_id: c.model_dump_json() for c in chunks.iter_chunks()}
        assert _vector_coverage(tmp_path) == coverage
        # The vector implementation also rejects projections at its public add boundary.
        assert vectors.add(projected) == 0
        assert vectors.count_rows() == len(eligible_body)
        with sqlite3.connect(path) as db:
            db.execute("VACUUM")
        rebuilt_bytes = path.stat().st_size
        logical = {kind: sum(len(json.dumps(row, ensure_ascii=False).encode()) for row in all_projected
                             if f"#projection:{kind}:" in row["chunk_id"]) for kind in ("entry", "row")}
        counts = {kind: sum(f"#projection:{kind}:" in row["chunk_id"] for row in all_projected)
                  for kind in logical}
        delta = full_bytes - legacy_bytes
        estimate = {kind: round(delta * logical[kind] / sum(logical.values()) / counts[kind], 2)
                    for kind in logical}
        catalog_count = len(deps.catalog.search("", k=1_000_000))
        observation_count = sum(table.rows for table in deps.observations.describe().tables)
        catalog_bytes = (deps.data_dir / "catalog.sqlite").stat().st_size
        parquet_bytes = sum(path.stat().st_size for path in (deps.data_dir / "parquet").rglob("*.parquet")
                            if path.parent.name != "zz-observation-history")
        eligible_entries = sum("#projection:entry:" in chunk.chunk_id for chunk in projected)
        cloud_counts = {"catalog_entries": round(150_000_000 * catalog_count / catalog_bytes),
                        "observation_rows": round(7_000_000 * observation_count / parquet_bytes)}
        cloud_bytes = round(cloud_counts["catalog_entries"] * eligible_entries / catalog_count * estimate["entry"]
                            + cloud_counts["observation_rows"] * estimate["row"])
        storage = {"current_projection_chunks": len(projected), "stored_projection_counts": counts,
                   "full_bytes": full_bytes, "legacy_bytes": legacy_bytes,
                   "projection_delta_bytes": delta, "rebuilt_bytes": rebuilt_bytes,
                   "estimated_bytes_per_entry_or_row": estimate,
                   "sample_catalog_count": catalog_count, "sample_observation_count": observation_count,
                   "sample_catalog_bytes": catalog_bytes, "sample_parquet_bytes": parquet_bytes,
                   "cloud_counts_estimated_from_task_sizes": cloud_counts,
                   "cloud_projection_bytes_estimate": cloud_bytes,
                   "cloud_formula": "eligible_entry_count * entry_bytes + observation_count * row_bytes",
                   "cloud_assumption": "150 MB catalog and 7 MB Parquet scaled by sample bytes per record; counts unverified",
                   "method": "VACUUM before/after removing production projections; allocate delta by JSON byte share"}
        with capsys.disabled():
            print("\nAUDIT 149 STORAGE\n" + json.dumps(storage, indent=2))
        _json(maple_m3["evidence"] / "storage.json", storage)
    finally:
        keyword.close()
        chunks.close()
