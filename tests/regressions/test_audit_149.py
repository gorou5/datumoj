class RecordingPlan(Crawler):
    """Frozen discovery only; fetching, validation and persistence stay real."""

    kind = "m3-recordings"

    def __init__(self, tasks):
        self.tasks = tasks

    def plan(self, ctx):
        return iter(self.tasks)


def _replay(deps, sid, tasks, routes):
    spec = deps.registry.get(sid)
    routes = {**routes, **{f"https://{host}/robots.txt": Recorded(status=404)
                          for host in {urlsplit(task.url).hostname for task in tasks}}}
    transport = ReplayTransport(routes)
    with PoliteHttpFetcher.from_spec(spec, transport=transport, now=lambda: SECOND,
                                    clock=lambda: 0.0, sleep=lambda _: None) as fetcher:
        report = deps.run_crawl(spec, RecordingPlan(tasks), CrawlDeps(
            raw=deps.raw, manifest=deps.manifest, fetcher=fetcher, now=lambda: SECOND,
            clock=lambda: 0.0, sleep=lambda _: None,
        ))
    assert not report.failures, report
    assert report.stop_reason in (None, f"因上限停止：max_files={len(tasks)}"), report
    assert report.new + report.unchanged == len({task.url for task in tasks})
    return {"source_id": sid, "requests": transport.requests, **vars(report)}


